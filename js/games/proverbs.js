        var buttons = [];
        var answered = false;

        choicesList.forEach(function (c) {
          var b = ctx.el('button', { class: 'g-choice pv-choice', type: 'button', text: c, onclick: function () { answer(c, b); } });
          buttons.push({ c: c, btn: b });
          choices.appendChild(b);
        });

        root.innerHTML = '';
        root.appendChild(ctx.el('div', { class: 'pv-wrap' }, [card, choices, explain, nextBtn]));

